-- 4. Habilitar Row Level Security (RLS) e Políticas Públicas para o App
alter table members_auth enable row level security;
alter table daily_presence enable row level security;
alter table pt_announcements enable row level security;

-- Políticas de acesso para a anon key (permite leitura e escrita pelo app da PT)
drop policy if exists "Leitura livre de membros" on members_auth;
create policy "Leitura livre de membros" on members_auth for select using (true);

drop policy if exists "Atualizacao de membros" on members_auth;
create policy "Atualizacao de membros" on members_auth for update using (true);

drop policy if exists "Leitura de presenca" on daily_presence;
create policy "Leitura de presenca" on daily_presence for select using (true);

drop policy if exists "Insercao de presenca" on daily_presence;
create policy "Insercao de presenca" on daily_presence for insert with check (true);

drop policy if exists "Atualizacao de presenca" on daily_presence;
create policy "Atualizacao de presenca" on daily_presence for update using (true);

drop policy if exists "Leitura de avisos" on pt_announcements;
create policy "Leitura de avisos" on pt_announcements for select using (true);

drop policy if exists "Insercao de avisos" on pt_announcements;
create policy "Insercao de avisos" on pt_announcements for insert with check (true);

drop policy if exists "Delecao de avisos" on pt_announcements;
create policy "Delecao de avisos" on pt_announcements for delete using (true);

-- 5. Habilitar Realtime nas tabelas para sincronizar no Windows de todos sem F5
begin;
  -- Adiciona tabelas na publicação do realtime do Supabase
  alter publication supabase_realtime add table daily_presence;
  alter publication supabase_realtime add table pt_announcements;
commit;
