-- 2. Tabela de Confirmação Diária & Anotações de Ausência
create table if not exists daily_presence (
  id bigint generated by default as identity primary key,
  player_id text not null references members_auth(id) on delete cascade,
  date date not null default current_date,
  status text not null default 'ready', -- 'ready', 'absent', 'office', 'late', 'raven', 'family'
  note text default '',                 -- Anotação caso não possa comparecer ou observação
  updated_at timestamp with time zone default timezone('utc'::text, now()),
  constraint unique_player_date unique (player_id, date)
);

-- 3. Tabela do Mural de Avisos da PT
create table if not exists pt_announcements (
  id bigint generated by default as identity primary key,
  author text not null,
  content text not null,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

